/**
 * Where an employee's salary is sent, and who is allowed to decide it.
 *
 * This is the one screen in the product that writes a payment destination
 * directly — no approval chain, no second signature. `POST /bank-change-requests`
 * is the employee's route and it can be governed by a workflow; the migration
 * path is HR verifying a legacy free-text record by hand and writing an ACTIVE
 * `EmployeeBankDetail` in a single click. If that click accepts a wrong number,
 * the money goes somewhere else and nothing in the system objects.
 *
 * So the assertion this file is built around is not "the button worked". It is
 * that a bad IBAN is REFUSED and the reason reaches the person typing it. The
 * backend suite (`finance-bank-migration.e2e-spec.ts`, 44 cases) already proves
 * the server refuses; what is untested until here is whether the refusal
 * survives the trip to the screen, because this page renders the structured
 * `errors` map rather than the flat `message` and a shape change there degrades
 * a precise sentence into "Failed to migrate".
 *
 * ## Four screens, one rule
 *
 * The chain is real and the specs follow it: branch banking countries decide
 * which countries an employee may bank in → the field config decides which
 * fields those countries demand → the bank master decides which banks exist
 * inside them → migration is where all three land on one person. Each describe
 * changes one link and asserts the change appears downstream, because that
 * coupling is invisible on any single screen.
 *
 * ## Facts this file encodes
 *
 *   • A candidate is an ACTIVE employee with a legacy `profile.bankName` and NO
 *     active bank detail. Migrating one removes it from that set permanently —
 *     there is no API that deactivates a detail — so the journey hires its own
 *     candidate rather than consuming the seeded one, and terminates it
 *     afterwards. Using EMP002 would make this file work exactly once per
 *     database.
 *   • The country picker on a migration card is rendered ONLY where the branch
 *     allows more than one banking country. With exactly one it is pre-selected
 *     and absent, which is why the branch-countries describe below turns HO
 *     from one country into two and watches the picker appear.
 *   • The `Autofill (dev)` button is gated on
 *     `process.env.NODE_ENV !== 'production'` and this suite runs a PRODUCTION
 *     build (`e2e/start-frontend.sh` → `next build`), so it is dead-code
 *     eliminated. Every IBAN here is generated by `omIban()` below, whose
 *     algorithm is copied from the backend spec's generator. A hand-written
 *     IBAN fails for the wrong reason and makes the test lie.
 */

